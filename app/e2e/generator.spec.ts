type Go = (page: Page) => Promise<void>;
const NEW_SCREENS: { name: string; h1: string | RegExp; go: Go }[] = [
  { name: 'Load with Create my plan', h1: 'Load protocol file', go: toLoad },
  { name: 'Question', h1: 'Did your care team give you a written rehab plan?', go: async (p) => { await toLoad(p); await press(p, 'Create my plan'); } },
  { name: 'Question with a date', h1: 'What was the date of your surgery?', go: async (p) => { await toLoad(p); await press(p, 'Create my plan'); await referralQuestions(p); } },
  { name: 'Question with the limit', h1: /Did your surgeon give a limit/, go: async (p) => { await toLoad(p); await press(p, 'Create my plan'); await referralQuestions(p); await p.getByLabel('Date of surgery').fill(ago(WEEK3)); await next(p); await radio(p, 'Left'); await next(p); await radio(p, 'Yes, my limit is'); } },
  { name: 'Summary', h1: 'Check your answers', go: (p) => toSummary(p) },
  { name: 'Referral', h1: 'No plan from the app', go: async (p) => { await toLoad(p); await press(p, 'Create my plan'); await radio(p, 'Yes'); await next(p); } },
  { name: 'Plan', h1: 'Your plan', go: toPlan },
  { name: 'Plan with Why this plan open', h1: 'Your plan', go: async (p) => { await toPlan(p); await p.getByRole('heading', { name: 'Why this plan' }).click(); await p.getByRole('list', { name: 'Rules behind your plan' }).getByRole('heading', { name: 'Heel slide', exact: true }).click(); } },
  { name: 'Confirm', h1: 'Confirm your plan', go: toConfirm },
  { name: 'Home with the plan', h1: 'Home', go: toHomeWithPlan },
  { name: 'Update my plan', h1: 'Update my plan', go: async (p) => { await toHomeWithPlan(p); await toUpdate(p); } },
  { name: 'Confirm the change', h1: 'Confirm the change', go: async (p) => { await toHomeWithPlan(p); await toUpdate(p); await radio(p, '2'); await radio(p, 'No swelling'); await p.getByLabel('Limit in degrees').fill('50'); await press(p, 'Check my plan'); } },
];

for (const size of [{ width: 390, height: 844 }, { width: 1280, height: 800 }]) {
  test.describe(`new screens at ${size.width} x ${size.height}`, () => {
    test.use({ viewport: size });
    for (const s of NEW_SCREENS) {
      test(`${s.name}: axe finds no violation, no horizontal scroll, the h1 holds the focus, every target is 48 px`, async ({ page }) => {
        await s.go(page);
        await h1(page, s.h1);
        const { violations } = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
        expect(violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target.join(' ')) }))).toEqual([]);
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
        if (!['Home with the plan', 'Load with Create my plan'].includes(s.name)) {
          const active = await focused(page);
          expect(active.tag === 'H1' || s.name.startsWith('Plan with') || s.name.startsWith('Question with')).toBe(true);
        }
        const small = await page.evaluate(() => {
          const out: string[] = [];
          const check = (el: Element, name: string) => {
            const b = el.getBoundingClientRect();
            if (b.width > 0 && b.height > 0 && (b.width < 47.5 || b.height < 47.5)) out.push(`${name} ${Math.round(b.width)}x${Math.round(b.height)}`);
          };
          document.querySelectorAll('button').forEach((el) => check(el, `button "${el.textContent?.trim()}"`));
          document.querySelectorAll('label').forEach((l) => {
            if (l.querySelector('input[type="checkbox"], input[type="radio"]')) check(l, `label "${l.textContent?.trim()}"`);
          });
          document.querySelectorAll('summary').forEach((el) => check(el, `summary "${el.textContent?.trim()}"`));
          return out;
        });
        expect(small).toEqual([]);
      });
    }
  });
}
