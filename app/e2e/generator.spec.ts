test('Create my plan: questions, plan, Why this plan, a real click on Confirm, and Home shows the plan', async ({ page }) => {
  await toLoad(page);
  await press(page, 'Create my plan');
  await expect.poll(() => focused(page)).toMatchObject({ tag: 'H1', text: 'Did your care team give you a written rehab plan?' });
  await expect(page.getByText('Question 1 of 11')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeDisabled();
  await radio(page, 'No'); await next(page);
  await expect.poll(() => focused(page)).toMatchObject({ tag: 'H1', text: 'Which operation did you have?' });
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(page.getByRole('radio', { name: 'No', exact: true })).toBeChecked();
  await next(page);
  await radio(page, 'MPFL reconstruction only'); await next(page);
  await radio(page, '18 or older'); await next(page);
  await radio(page, 'No'); await next(page);
  await radio(page, 'Yes'); await next(page);
  await radio(page, 'No'); await next(page);
  await page.getByLabel('Date of surgery').fill(ago(WEEK3)); await next(page);
  await radio(page, 'Left'); await next(page);
  await radio(page, 'Yes, my limit is');
  await page.getByLabel('Limit in degrees').fill('60'); await next(page);
  await expect(page.getByRole('checkbox')).toHaveCount(9);
  await next(page);
  await radio(page, '2'); await radio(page, 'No swelling'); await next(page);
  await expect.poll(() => focused(page)).toMatchObject({ tag: 'H1', text: 'Check your answers' });
  // Nothing is stored before Confirm.
  expect(await readStore(page, 'protocol')).toHaveLength(0);
  expect(await readInputs(page)).toHaveLength(0);

  await press(page, 'Make my plan');
  await expect.poll(() => focused(page)).toMatchObject({ tag: 'H1', text: 'Your plan' });
  await expect(page.getByText(GENERATED_BANNER)).toBeVisible();
  await page.getByRole('heading', { name: 'Why this plan' }).click();
  const rules = page.getByRole('list', { name: 'Rules behind your plan' });
  await expect(rules.getByRole('heading', { name: 'Straight leg raise' })).toBeVisible();
  await rules.getByRole('heading', { name: 'Dose of the strengthening exercise' }).click();
  const open = page.locator('.why-details[open]');
  await expect(open.getByText('Expert opinion (OPINION)')).toBeVisible();
  await expect(open.getByText(/P2: Cincinnati/)).toBeVisible();
  await expect(open.getByText(/2 sets of 10 to 15, then 3 sets as tolerated/).first()).toBeVisible();
  await expect(open.getByText(/8 to 25/).first()).toBeVisible();
  await expect(page.getByRole('list', { name: 'Not in your plan, and why' }).getByRole('heading', { name: 'Mini squat' })).toBeVisible();
  expect(await readStore(page, 'protocol')).toHaveLength(0);

  await press(page, 'Use this plan');
  await expect.poll(() => focused(page)).toMatchObject({ tag: 'H1', text: 'Confirm your plan' });
  expect(await readStore(page, 'protocol')).toHaveLength(0);
  await press(page, 'Confirm'); // a real click: Playwright sends a trusted event
  await expectScreen(page, 'Home');
  await expectBanners(page, { example: false });
  await expect(page.getByRole('note').filter({ hasText: GENERATED_BANNER })).toBeVisible();
  await expect(page.getByText('Generated by the app from published protocols', { exact: true })).toBeVisible();

  const [row] = (await readStore(page, 'protocol')) as { raw: string }[];
  const stored = JSON.parse(row!.raw);
  expect(stored.generated.on).toBe(iso(new Date()));
  expect(stored.generated.rules).toEqual(expect.arrayContaining(['W1', 'SLR', 'RANGE_SURGEON']));
  expect(stored.approvedOn).toBeUndefined();
  const [inputs] = (await readInputs(page)) as { inputs: Record<string, unknown> }[];
  expect(inputs!.inputs).toMatchObject({ surgeryDate: ago(WEEK3), side: 'left', surgeonLimit: { kind: 'degrees', degrees: 60 } });
  expect(inputs!.inputs).not.toHaveProperty('pain');
  await page.reload();
  await expectScreen(page, 'Home');
  await expect(page.getByRole('button', { name: 'Update my plan' })).toBeVisible();
});

