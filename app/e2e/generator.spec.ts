test('typing 29, 10 and 2026 stores 2026-10-29 and says it in words, and a click elsewhere or a blur never changes it', async ({ page }) => {
  await page.clock.setFixedTime(new Date(2026, 10, 18, 10, 0, 0)); // today is 18 November 2026
  await toLoadAny(page);
  await press(page, 'Create my plan');
  await referralQuestions(page);
  await h1(page, 'Your surgeon');
  await page.getByLabel('Day', { exact: true }).pressSequentially('29');
  await page.getByLabel('Month', { exact: true }).pressSequentially('10');
  await page.getByLabel('Year', { exact: true }).pressSequentially('2026');
  const words = page.getByText('You chose 29 October 2026, week 2 (the third week after surgery).');
  await expect(words).toBeVisible();
  const same = async () => {
    await expect(page.getByLabel('Day', { exact: true })).toHaveValue('29');
    await expect(page.getByLabel('Month', { exact: true })).toHaveValue('10');
    await expect(page.getByLabel('Year', { exact: true })).toHaveValue('2026');
    await expect(words).toBeVisible();
  };
  await page.getByRole('heading', { level: 1 }).click(); // a click elsewhere
  await same();
  await page.getByLabel('Year', { exact: true }).focus();
  await page.getByLabel('Day', { exact: true }).focus(); // a blur of the year field
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  await same();
  await pick(page, QUESTION.side, 'Left');
  await pick(page, QUESTION.limit, 'No limit');
  await press(page, 'Continue to today');
  await radio(page, '2'); await radio(page, 'No swelling');
  await press(page, 'Check my answers');
  await expect(page.getByText('29 October 2026, week 2 (the third week after surgery)')).toBeVisible();
  await press(page, 'Make my plan');
  await press(page, 'Use this plan');
  await press(page, 'Confirm');
  await expectScreen(page, 'Home');
  const [inputs] = (await readInputs(page)) as { inputs: Record<string, unknown> }[];
  expect(inputs!.inputs).toMatchObject({ surgeryDate: '2026-10-29' });
});

test('the clock moves and the phase stays 1 until Update my plan and Confirm, and Confirm moves it to 2 with the flag at its default (on)', async ({ page }) => {
  await toHomeWithPlan(page);
  const [before] = (await readStore(page, 'protocol')) as { raw: string }[];
  // Fix the date of the page 4 weeks later, then reload. The stored plan is the same.
  await page.clock.setFixedTime(new Date(Date.now() + 28 * 86_400_000));
  await page.reload();
  await expectScreen(page, 'Home');
  await expect(page.getByText('1, Protection')).toBeVisible();
  await expect(page.getByText('Review your plan with your care team')).toBeVisible(); // week 7: the review date has passed
  const [afterReload] = (await readStore(page, 'protocol')) as { raw: string }[];
  expect(afterReload!.raw).toBe(before!.raw);

  const answerNextStage = async () => {
    await toUpdate(page);
    await radio(page, '2'); await radio(page, 'No swelling');
    await radio(page, 'Yes');
    // The extended items are on by default: the three questions for the next exercises show after the answer yes.
    for (const legend of ['Do you walk without crutches?', 'Can you lift your leg with a straight knee, with no bend in the knee while the leg is up?', 'Did your surgeon say that you can do knee straightening exercises while you sit?']) {
      await page.getByRole('group', { name: legend }).getByRole('radio', { name: 'Yes', exact: true }).check();
    }
    await press(page, 'Check my plan');
    await expectScreen(page, 'Confirm the change');
  };
  await answerNextStage();
  // The screen offers Confirm. Nothing is saved before the click.
  await expect(page.getByText('Ask your care team about the next stage.')).toHaveCount(0);
  expect(((await readStore(page, 'protocol')) as { raw: string }[])[0]!.raw).toBe(before!.raw);
  await press(page, 'Keep my plan');
  await expectScreen(page, 'Home');
  const [kept] = (await readStore(page, 'protocol')) as { raw: string }[];
  expect(kept!.raw).toBe(before!.raw);
  expect(JSON.parse(kept!.raw).activePhase).toBe(1);

  await answerNextStage();
  await press(page, 'Confirm');
  await expectScreen(page, 'Home');
  const [after] = (await readStore(page, 'protocol')) as { raw: string }[];
  expect(JSON.parse(after!.raw).activePhase).toBe(2);
});

test('Keep my plan changes nothing, and Confirm saves a lower limit after a real click', async ({ page }) => {
  await toHomeWithPlan(page);
  const [before] = (await readStore(page, 'protocol')) as { raw: string }[];
  await toUpdate(page);
  await radio(page, '2'); await radio(page, 'No swelling');
  await page.getByLabel('Limit in degrees').fill('50');
  await press(page, 'Check my plan');
  await expectScreen(page, 'Confirm the change');
  const row = page.locator('.change-row', { hasText: 'Knee-bend limit in your plan' });
  await expect(row.locator('.before')).toHaveText('60 degrees');
  await expect(row.locator('.after')).toHaveText('50 degrees');
  expect(((await readStore(page, 'protocol')) as { raw: string }[])[0]!.raw).toBe(before!.raw);
  await press(page, 'Keep my plan');
  await expectScreen(page, 'Home');
  expect(((await readStore(page, 'protocol')) as { raw: string }[])[0]!.raw).toBe(before!.raw);

  await toUpdate(page);
  await radio(page, '2'); await radio(page, 'No swelling');
  await page.getByLabel('Limit in degrees').fill('50');
  await press(page, 'Check my plan');
  await press(page, 'Confirm');
  await expectScreen(page, 'Home');
  const after = JSON.parse(((await readStore(page, 'protocol')) as { raw: string }[])[0]!.raw);
  expect(after.phases[0].exercises.find((e: { kind: string }) => e.kind === 'heel-slide').maxFlexion).toBe(50);
});

