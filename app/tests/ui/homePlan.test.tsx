// Home, the plan that the app made: "Update my plan" and the B3 phase review card (adaptation design 5.4, 5.5).
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { loadProtocol, type Protocol } from '../../src/lib/protocol';
import { generateProtocol, type GeneratorInputs } from '../../src/lib/protocolGen';
import { Home } from '../../src/ui/Home';
import { saveGeneratorInputs, saveSession } from '../../src/lib/storage';
import { freshDb, protocolText, sessionInput } from './helpers';
import { hasVerdictWord } from './verdict';

beforeEach(() => localStorage.clear());
afterEach(cleanup);

const inputs: GeneratorInputs = {
  writtenPlan: 'no', procedure: 'mpflr-only', ageBand: '18-plus', bothKnees: false, firstSurgery: 'yes', specialRules: 'no',
  surgeryDate: '2026-10-15', side: 'left', surgeonLimit: { kind: 'degrees', degrees: 60 }, phaseClearance: 'no', redFlags: {}, pain: 2, swelling: 'none',
};
/** A generated plan made on 2026-11-08. Its phase 1 review date is the surgery date plus 6 weeks: 2026-11-26. */
const generated = (): Protocol => {
  const r = generateProtocol(inputs, '2026-11-08');
  if (r.kind !== 'protocol') throw new Error('expected a plan');
  return r.protocol;
};
const careTeam = (reviewDate?: string): Protocol => {
  const r = loadProtocol(protocolText(), 'demo');
  if (!r.ok) throw new Error(r.error.message);
  return { ...r.protocol, phases: r.protocol.phases.map((p) => (p.id === 1 ? { ...p, reviewDate } : p)) };
};

function setup(p: Protocol, day: string, props: Record<string, unknown> = {}) {
  const phase = p.phases.find((x) => x.id === p.activePhase);
  const handlers = { onStart: vi.fn(), onLoadProtocol: vi.fn(), onOpenData: vi.fn(), onUpdatePlan: vi.fn() };
  const view = render(<Home protocol={p} phase={phase} activePhase={p.activePhase} db={freshDb()} now={() => new Date(`${day}T10:00:00`)} {...handlers} {...props} />);
  return { ...handlers, view };
}
const CARD = 'Review your plan with your care team';

describe('Home, a plan that the app made', () => {
  it('shows who wrote it, and no approval', () => {
    setup(generated(), '2026-11-10');
    expect(screen.getByText('Generated by the app from published protocols')).toBeInTheDocument();
    expect(screen.getByText('No clinician approval recorded')).toBeInTheDocument();
  });

  it('shows Update my plan, and it opens the update', () => {
    const { onUpdatePlan } = setup(generated(), '2026-11-10');
    fireEvent.click(screen.getByRole('button', { name: 'Update my plan' }));
    expect(onUpdatePlan).toHaveBeenCalledTimes(1);
  });

  it('shows no Update my plan for a plan from a care team file', () => {
    setup(careTeam('2026-03-01'), '2026-03-20');
    expect(screen.queryByRole('button', { name: 'Update my plan' })).toBeNull();
  });

  it('shows no Update my plan without the handler', () => {
    setup(generated(), '2026-11-10', { onUpdatePlan: undefined });
    expect(screen.queryByRole('button', { name: 'Update my plan' })).toBeNull();
  });
});

describe('Home, the phase review card (B3)', () => {
  it('shows no card before the review date', () => {
    setup(generated(), '2026-11-25');
    expect(screen.queryByText(CARD)).toBeNull();
  });

  it('shows the card on the review date, with the date of the plan and one Update my plan button', () => {
    const { onUpdatePlan } = setup(generated(), '2026-11-26');
    expect(screen.getByText(CARD)).toBeInTheDocument();
    expect(screen.getByText(/The review date in your plan is/)).toHaveTextContent('2026-11-26');
    expect(screen.getAllByRole('button', { name: 'Update my plan' })).toHaveLength(1);
    fireEvent.click(screen.getByRole('button', { name: 'Update my plan' }));
    expect(onUpdatePlan).toHaveBeenCalledTimes(1);
  });

  it('keeps showing the card after the review date', () => {
    setup(generated(), '2026-12-20');
    expect(screen.getByText(CARD)).toBeInTheDocument();
  });

  it('uses the date of the device clock in the local time zone', () => {
    setup(generated(), '2026-11-26');
    expect(screen.getByText(CARD)).toBeInTheDocument();
  });

  it('offers Export for my care team and no Update my plan for a care team file', async () => {
    const db = freshDb();
    await saveSession(db, sessionInput());
    const { onOpenData } = setup(careTeam('2026-03-01'), '2026-03-20', { db });
    await act(async () => void (await new Promise((r) => setTimeout(r, 30))));
    expect(screen.getByText(CARD)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Update my plan' })).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Export for my care team' }));
    expect(onOpenData).toHaveBeenCalledTimes(1);
  });

  it('offers no Export button when there are no sessions (A-09)', async () => {
    setup(careTeam('2026-03-01'), '2026-03-20');
    await act(async () => void (await new Promise((r) => setTimeout(r, 30))));
    expect(screen.getByText(CARD)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Export for my care team' })).toBeNull();
  });

  it('shows no card when the plan has no review date', () => {
    setup(careTeam(undefined), '2026-03-20');
    expect(screen.queryByText(CARD)).toBeNull();
  });

  it('is neutral: no verdict word, no inline style, no goal', () => {
    const { view } = setup(generated(), '2026-11-26');
    expect(hasVerdictWord(view.container.textContent ?? '')).toBeNull();
    expect(view.container.querySelector('[style]')).toBeNull();
  });
});

describe('Home, after week 11 (A-03)', () => {
  const later = '2027-01-14'; // week 13 after the surgery date 2026-10-15
  it('says the app has no plan and shows no Update my plan, in the card and in the protocol card', async () => {
    const db = freshDb();
    await saveGeneratorInputs(db, inputs as never);
    setup(generated(), later, { db });
    await act(async () => void (await new Promise((r) => setTimeout(r, 30))));
    expect(screen.getByText('The app has no plan after week 11. Contact your care team for your next plan.')).toBeInTheDocument();
    expect(screen.queryByText(/check your plan again/)).toBeNull();
    expect(screen.queryByRole('button', { name: 'Update my plan' })).toBeNull();
  });

  it('keeps the update text and the button up to week 11', async () => {
    const db = freshDb();
    await saveGeneratorInputs(db, inputs as never);
    setup(generated(), '2026-12-20', { db });
    await act(async () => void (await new Promise((r) => setTimeout(r, 30))));
    expect(screen.getByText(/check your plan again/)).toBeInTheDocument();
    expect(screen.getAllByRole('button', { name: 'Update my plan' })).toHaveLength(1);
  });
});
