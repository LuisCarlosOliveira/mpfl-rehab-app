// The whole app with a real database (fake-indexeddb): Create my plan, the confirmation, Update my plan, the referral,
// patient mode, erase, and the pain stop between sets with the protocol threshold.
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { GENERATED_BANNER } from '../../src/lib/mode';
import { PAUSE_MESSAGE } from '../../src/lib/safety';
import { loadGeneratorInputs, loadStoredProtocol, markPrivacyNoticeSeen, saveProtocol } from '../../src/lib/storage';
import { App } from '../../src/ui/App';
import { freshDb, mockSource, playRep, protocolText, readyLeg } from './helpers';
import { installDialogStub } from './t11helpers';

vi.mock('../../src/lib/protocol/trustedFlag', () => ({ trustedFlag: () => (globalThis as { __trust?: boolean }).__trust === true }));
const trust = (on: boolean) => ((globalThis as { __trust?: boolean }).__trust = on);

beforeEach(() => {
  localStorage.clear();
  installDialogStub();
  trust(true);
});
afterEach(() => {
  cleanup();
  trust(false);
});

// The clock of the app. Local time, so the calendar date is 2026-11-08 in any zone.
const NOW = () => new Date(2026, 10, 8, 10, 0, 0);
const heading = (name: string | RegExp) => screen.findByRole('heading', { level: 1, name });
const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }));
const choose = (name: string | RegExp) => fireEvent.click(screen.getByRole('radio', { name }));
const next = () => click('Next');
const type = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } });

async function openLoad(mode: 'demo' | 'patient' = 'demo') {
  const db = freshDb();
  markPrivacyNoticeSeen();
  const view = render(<App db={db} mode={mode} source={mockSource()} now={NOW} />);
  await heading('Load protocol file');
  return { db, ...view };
}

/** Answers the questions up to the summary. The date 2026-10-15 is week 3. */
function answerAll(date = '2026-10-15', limit = '60') {
  choose('No'); next();
  choose('MPFL reconstruction only'); next();
  choose('18 or older'); next();
  choose('No'); next();
  choose('Yes'); next();
  choose('No'); next();
  type('Date of surgery', date); next();
  choose('Left'); next();
  choose(/Yes, my limit is/); type('Limit in degrees', limit); next();
  next();
  choose('2'); choose('No swelling'); next();
}

/** Create my plan to the confirmation screen. */
async function toConfirm() {
  const ctx = await openLoad();
  click('Create my plan');
  await heading('Did your care team give you a written rehab plan?');
  answerAll();
  await heading('Check your answers');
  click('Make my plan');
  await heading('Your plan');
  click('Use this plan');
  await heading('Confirm your plan');
  return ctx;
}

describe('Create my plan, in the whole app', () => {
  it('goes from the Load screen to a stored plan on Home, and saves nothing before Confirm', async () => {
    const { db } = await toConfirm();
    expect(await loadStoredProtocol(db, 'demo')).toBeNull();
    expect(await loadGeneratorInputs(db)).toBeNull();
    click('Confirm');
    await heading('Home');
    const stored = await loadStoredProtocol(db, 'demo');
    expect(stored?.ok && stored.protocol.generated?.on).toBe('2026-11-08');
    expect(stored?.ok && stored.protocol.approvedOn).toBeUndefined();
    expect(await loadGeneratorInputs(db)).toMatchObject({ surgeryDate: '2026-10-15' });
    expect(screen.getByText(GENERATED_BANNER)).toBeInTheDocument();
    expect(screen.getByText('Generated by the app from published protocols')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Update my plan' })).toBeInTheDocument();
  });

  it('shows the plan with Why this plan before it is confirmed, and Back returns to the summary', async () => {
    const ctx = await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    answerAll();
    click('Make my plan');
    await heading('Your plan');
    expect(screen.getByText('Why this plan')).toBeInTheDocument();
    expect(screen.queryByText(GENERATED_BANNER, { selector: '.banner' })).toBeNull();
    click('Back');
    await heading('Check your answers');
    expect(await loadStoredProtocol(ctx.db, 'demo')).toBeNull();
  });

  it('does not save when the click is not a click of a person', async () => {
    trust(false);
    const { db } = await toConfirm();
    click('Confirm');
    expect(await screen.findByRole('alert')).toHaveTextContent(/did not read this as a click of a person/i);
    expect(await loadStoredProtocol(db, 'demo')).toBeNull();
    await heading('Confirm your plan');
  });

  it('Do not save this plan returns to the Load screen and saves nothing', async () => {
    const { db } = await toConfirm();
    click('Do not save this plan');
    await heading('Load protocol file');
    expect(await loadStoredProtocol(db, 'demo')).toBeNull();
  });

  it('keeps the plan after a reload, with the banner', async () => {
    const { db, unmount } = await toConfirm();
    click('Confirm');
    await heading('Home');
    unmount();
    render(<App db={db} mode="demo" source={mockSource()} now={NOW} />);
    await heading('Home');
    expect(screen.getByText(GENERATED_BANNER)).toBeInTheDocument();
  });

  it('refers at once for a combined operation, shows no plan and stores nothing', async () => {
    const { db } = await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    choose('No'); next();
    choose('MPFL reconstruction with another procedure'); next();
    await heading('No plan from the app');
    expect(screen.getByText(/MPFL reconstruction with no other procedure/)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Use this plan' })).toBeNull();
    expect(await loadStoredProtocol(db, 'demo')).toBeNull();
    expect(await loadGeneratorInputs(db)).toBeNull();
    click('Back to the start');
    await heading('Load protocol file');
  });

  it('a red flag at the summary gives the refusal and stores nothing', async () => {
    const { db } = await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    choose('No'); next();
    choose('MPFL reconstruction only'); next();
    choose('18 or older'); next();
    choose('No'); next();
    choose('Yes'); next();
    choose('No'); next();
    type('Date of surgery', '2026-10-15'); next();
    choose('Left'); next();
    choose('No limit'); next();
    fireEvent.click(screen.getByRole('checkbox', { name: 'Your knee catches or locks.' }));
    next();
    choose('2'); choose('No swelling'); next();
    click('Make my plan');
    await heading('No plan from the app');
    expect(screen.getByRole('alert')).toHaveTextContent('Contact your care team');
    expect(await loadStoredProtocol(db, 'demo')).toBeNull();
  });

  it('a plan at week 12 gives the refusal', async () => {
    await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    answerAll('2026-08-01');
    // from week 7 a question about the next stage comes first
    await heading(/Has your surgeon or physiotherapist said/);
    choose('No'); next();
    click('Make my plan');
    await heading('No plan from the app');
    expect(screen.getByText(/no plan after week 11/)).toBeInTheDocument();
  });

  it('shows no Create my plan in patient mode', async () => {
    await openLoad('patient');
    expect(screen.queryByRole('button', { name: 'Create my plan' })).toBeNull();
  });
});

describe('Patient mode refuses a plan that the app made', () => {
  it('shows the named error for a stored plan with no approval, and does not open Home', async () => {
    const db = freshDb();
    markPrivacyNoticeSeen();
    const generated = { ...JSON.parse(protocolText()), example: undefined, approvedOn: undefined, authoredBy: 'Generated by the app from published protocols', generated: { on: '2026-11-08', rules: ['W1'] } };
    await db.protocol.put({ key: 'current', raw: JSON.stringify(generated), savedAt: '2026-11-08T00:00:00.000Z' });
    render(<App db={db} mode="patient" source={mockSource()} now={NOW} />);
    await heading('Load protocol file');
    expect(screen.getByRole('alert')).toHaveTextContent('A plan that the app made has no clinician approval');
  });
});

describe('Update my plan, in the whole app', () => {
  async function openHomeWithPlan() {
    const ctx = await toConfirm();
    click('Confirm');
    await heading('Home');
    return ctx;
  }
  const fillToday = () => {
    choose('2');
    choose('No swelling');
  };

  it('Keep my plan changes nothing, byte for byte', async () => {
    const { db } = await openHomeWithPlan();
    const before = (await db.protocol.get('current'))!.raw;
    click('Update my plan');
    await heading('Update my plan');
    await screen.findByRole('button', { name: 'Check my plan' });
    fillToday();
    fireEvent.change(screen.getByLabelText('Limit in degrees'), { target: { value: '50' } });
    click('Check my plan');
    await heading('Confirm the change');
    expect(screen.getByText(/Knee-bend limit in your plan/)).toBeInTheDocument();
    expect((await db.protocol.get('current'))!.raw).toBe(before);
    click('Keep my plan');
    await heading('Home');
    expect((await db.protocol.get('current'))!.raw).toBe(before);
  });

  it('Confirm saves a lower limit after a click of a person', async () => {
    const { db } = await openHomeWithPlan();
    click('Update my plan');
    await screen.findByRole('button', { name: 'Check my plan' });
    fillToday();
    fireEvent.change(screen.getByLabelText('Limit in degrees'), { target: { value: '50' } });
    click('Check my plan');
    await heading('Confirm the change');
    click('Confirm');
    await heading('Home');
    const r = await loadStoredProtocol(db, 'demo');
    expect(r?.ok && r.protocol.phases[0]!.exercises.find((e) => e.kind === 'heel-slide')?.maxFlexion).toBe(50);
    expect(await loadGeneratorInputs(db)).toMatchObject({ surgeonLimit: { kind: 'degrees', degrees: 50 } });
  });

  it('a later date changes nothing until Update my plan and Confirm: the phase stays 1', async () => {
    const { db, unmount } = await openHomeWithPlan();
    unmount();
    const later = () => new Date(2026, 11, 20, 10, 0, 0); // week 9 after surgery
    render(<App db={db} mode="demo" source={mockSource()} now={later} />);
    await heading('Home');
    expect(screen.getByText('1, Protection')).toBeInTheDocument();
    const r = await loadStoredProtocol(db, 'demo');
    expect(r?.ok && r.protocol.activePhase).toBe(1);
  });

  it('the next stage is held with the flag off, and the stored plan stays', async () => {
    const { db, unmount } = await openHomeWithPlan();
    const before = (await db.protocol.get('current'))!.raw;
    unmount();
    const later = () => new Date(2026, 11, 20, 10, 0, 0);
    render(<App db={db} mode="demo" source={mockSource()} now={later} />);
    await heading('Home');
    click('Update my plan');
    await screen.findByRole('button', { name: 'Check my plan' });
    fillToday();
    choose('Yes');
    click('Check my plan');
    await heading('Confirm the change');
    expect(screen.getByText('Ask your care team about the next stage.')).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Confirm' })).toBeNull();
    click('Keep my plan');
    await heading('Home');
    expect((await db.protocol.get('current'))!.raw).toBe(before);
  });

  it('shows the review card on the review date and Update my plan opens the update', async () => {
    const { db, unmount } = await openHomeWithPlan();
    unmount();
    const review = () => new Date(2026, 10, 26, 10, 0, 0); // the surgery date plus 6 weeks
    render(<App db={db} mode="demo" source={mockSource()} now={review} />);
    await heading('Home');
    expect(screen.getByText('Review your plan with your care team')).toBeInTheDocument();
    click('Update my plan');
    await heading('Update my plan');
  });

  it('erase removes the stored answers with everything else', async () => {
    const { db } = await openHomeWithPlan();
    expect(await db.generatorInputs.count()).toBe(1);
    click('My data');
    await heading('My data');
    click('Erase all my data');
    click('Erase my data');
    await waitFor(() => expect(screen.getByRole('heading', { level: 1, name: 'Privacy' })).toBeInTheDocument());
    expect(await db.generatorInputs.count()).toBe(0);
    expect(await db.protocol.count()).toBe(0);
  });
});

describe('Pain stop between sets, with the threshold of the protocol (T24a wiring)', () => {
  const heel = { kind: 'heel-slide', sets: 2, reps: 1, targetFlexion: 60, maxFlexion: 90, returnWithinDeg: 18, minRepSeconds: 2, source: 'test' };
  async function toSession(over: Record<string, unknown>) {
    const db = freshDb();
    markPrivacyNoticeSeen();
    await saveProtocol(db, protocolText({ phases: [{ id: 1, name: 'Protection', exercises: [heel] }], ...over }), 'demo');
    const source = mockSource();
    render(<App db={db} mode="demo" source={source} now={NOW} />);
    await heading('Home');
    click('Start Heel slide');
    await heading('Check before you exercise');
    click(/none of these apply/i);
    await heading('Set up the camera');
    click('Next: set up the camera');
    click('Start camera');
    await screen.findByRole('button', { name: 'Start exercise' });
    // Setup measures the resting leg. Session then has a baseline, so reps can count.
    for (let t = 0; t < 30_000 && screen.queryByRole('heading', { level: 1, name: 'Heel slide' }) === null; t += 100) {
      act(() => source.emit(readyLeg(), t));
    }
    await heading('Heel slide');
    return source;
  }

  it('stops the session with the care team message when the answer is at the protocol threshold', async () => {
    const source = await toSession({ painPauseThreshold: 5 });
    playRep(source, 'left', 60, 60_000);
    choose('5');
    expect(await screen.findByText(PAUSE_MESSAGE)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Start next set' })).toBeNull();
  });

  it('stops for an answer above the threshold too', async () => {
    const source = await toSession({ painPauseThreshold: 5 });
    playRep(source, 'left', 60, 60_000);
    choose('6');
    expect(await screen.findByText(PAUSE_MESSAGE)).toBeInTheDocument();
  });

  it('does not stop for an answer below the threshold', async () => {
    const source = await toSession({ painPauseThreshold: 5 });
    playRep(source, 'left', 60, 60_000);
    choose('4');
    expect(screen.queryByText(PAUSE_MESSAGE)).toBeNull();
    expect(screen.getByRole('button', { name: 'Start next set' })).toBeInTheDocument();
  });

  // Audit 3, H1: the FR12 floor of 7 applies between sets even when the protocol has no threshold.
  it('stops at the floor of 7 without a threshold in the protocol, also for the answer 9', async () => {
    const source = await toSession({});
    playRep(source, 'left', 60, 60_000);
    choose('9');
    expect(await screen.findByText(PAUSE_MESSAGE)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Start next set' })).toBeNull();
  });

  it('does not stop at 6 without a threshold in the protocol', async () => {
    const source = await toSession({});
    playRep(source, 'left', 60, 60_000);
    choose('6');
    expect(screen.queryByText(PAUSE_MESSAGE)).toBeNull();
    expect(screen.getByRole('button', { name: 'Start next set' })).toBeInTheDocument();
  });
});

// R3-04: the Back button of the browser inside the questions goes one question back and keeps the answers.
// It still never reaches Setup or Session (tests/ui/appBack.test.tsx holds that guarantee).
describe('Back of the browser inside the questions', () => {
  const browserBack = () =>
    act(async () => {
      window.history.back();
      await new Promise((r) => setTimeout(r, 30));
    });

  it('goes one question back with the answers kept, and from the first question to the Load screen', async () => {
    await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    choose('No'); next();
    await heading('Which operation did you have?');
    choose('MPFL reconstruction only'); next();
    await heading('How old are you?');
    await browserBack();
    await heading('Which operation did you have?');
    expect(screen.getByRole('radio', { name: 'MPFL reconstruction only' })).toBeChecked();
    await browserBack();
    await heading('Did your care team give you a written rehab plan?');
    expect(screen.getByRole('radio', { name: 'No' })).toBeChecked();
    await browserBack();
    await heading('Load protocol file');
  });

  it('goes from "Check your answers" to the last question, and the answers stay', async () => {
    await openLoad();
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    answerAll();
    await heading('Check your answers');
    await browserBack();
    await heading('How is your knee today?');
    expect(screen.getByRole('radio', { name: '2' })).toBeChecked();
    next();
    await heading('Check your answers');
    expect(screen.getByText('Pain 2 out of 10, no swelling')).toBeInTheDocument();
  });

  it('goes Home from the first question when a plan is stored', async () => {
    const db = freshDb();
    markPrivacyNoticeSeen();
    await saveProtocol(db, protocolText(), 'demo');
    render(<App db={db} mode="demo" source={mockSource()} now={NOW} />);
    await heading('Home');
    click('Load a new protocol file');
    await heading('Load protocol file');
    click('Create my plan');
    await heading('Did your care team give you a written rehab plan?');
    await browserBack();
    await heading('Home');
  });
});
