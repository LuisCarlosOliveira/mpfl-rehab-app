import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { draftOf, type PlanDraft } from '../../src/lib/planView';
import { generateProtocol, RULES, type GeneratorInputs } from '../../src/lib/protocolGen';
import { PlanResult } from '../../src/ui/PlanResult';
import { hasVerdictWord } from './verdict';

afterEach(cleanup);

const TODAY = '2026-11-08';
const inputs = (over: Partial<GeneratorInputs> = {}): GeneratorInputs => ({
  writtenPlan: 'no', procedure: 'mpflr-only', ageBand: '18-plus', bothKnees: false, firstSurgery: 'yes', specialRules: 'no',
  surgeryDate: '2026-10-15', side: 'left', surgeonLimit: { kind: 'degrees', degrees: 60 }, phaseClearance: 'no', redFlags: {}, pain: 2, swelling: 'none',
  ...over,
});
const draftFor = (over: Partial<GeneratorInputs> = {}) => {
  const i = inputs(over);
  const d = draftOf(generateProtocol(i, TODAY), 'create', i);
  if (d.kind !== 'plan') throw new Error('expected a plan');
  return d as Extract<PlanDraft, { kind: 'plan' }>;
};

function setup(over: Partial<GeneratorInputs> = {}) {
  const onUse = vi.fn();
  const onBack = vi.fn();
  const view = render(<PlanResult draft={draftFor(over)} onUse={onUse} onBack={onBack} />);
  return { onUse, onBack, view };
}

describe('PlanResult', () => {
  it('has the heading, the label of the design and no approval text', () => {
    setup();
    expect(screen.getByRole('heading', { level: 1, name: 'Your plan' })).toBeInTheDocument();
    expect(screen.getByText('Generated by the app from published protocols. Not approved by a clinician.')).toBeInTheDocument();
  });

  it('shows the exercises of the plan with the numbers of the plan only', () => {
    setup();
    const list = screen.getByRole('list', { name: 'Exercises in your plan' });
    expect(within(list).getByText('Straight leg raise')).toBeInTheDocument();
    expect(within(list).getByText('Heel slide')).toBeInTheDocument();
    // The straight leg raise shows the whole dose range of P2. The heel slide has no dose in the guideline, so its row asks the care team.
    expect(within(list).getAllByText('2 sets of 10 to 15, then 3 sets as tolerated')).toHaveLength(1);
    expect(within(list).getAllByText('How many: ask your care team')).toHaveLength(1);
    expect(list.textContent).not.toMatch(/undefined|NaN|2 sets of 10 reps/);
    expect(within(list).getByText('Limit 60 degrees')).toBeInTheDocument();
  });

  it('says why there is no heel slide when the limit is below the minimum (R3 heel note)', () => {
    setup({ surgeonLimit: { kind: 'degrees', degrees: 20 } });
    const list = screen.getByRole('list', { name: 'Exercises in your plan' });
    expect(within(list).queryByText('Heel slide')).toBeNull();
    const note = screen.getByText(/^Heel slide:/);
    expect(note.closest('[role="note"]')).not.toBeNull();
    expect(note).toHaveTextContent(`below ${RULES.ENG_TARGET.values.minLimit} degrees`);
    expect(note).not.toHaveTextContent('ask your surgeon for a knee-bend limit');
  });

  it('shows the heel slide note as a visible note when the person gave no limit', () => {
    setup({ surgeonLimit: { kind: 'unknown' } });
    const note = screen.getByText(/^Heel slide:/);
    expect(note.closest('[role="note"]')).not.toBeNull();
    expect(note).toHaveTextContent('ask your surgeon for a knee-bend limit');
  });

  it('shows no heel slide and says ask your surgeon when the person gave no limit', () => {
    setup({ surgeonLimit: { kind: 'unknown' } });
    const list = screen.getByRole('list', { name: 'Exercises in your plan' });
    expect(within(list).queryByText('Heel slide')).toBeNull();
    expect(screen.getByText(/Heel slide: ask your surgeon/)).toBeInTheDocument();
  });

  it('closes Why this plan at first, and opens it to every rule with its source, level and caveat', () => {
    const { view } = setup();
    const details = view.container.querySelector('details') as HTMLDetailsElement;
    expect(details.open).toBe(false);
    expect(within(details).getByText('Why this plan')).toBeInTheDocument();
    for (const id of ['W1', 'PH1', 'SLR', 'HEEL', 'RANGE_SURGEON', 'REVIEW'] as const) {
      const rule = RULES[id];
      const entry = screen.getByRole('heading', { name: rule.title, level: 3 }).closest('li') as HTMLElement;
      expect(entry).toHaveTextContent(rule.text);
      expect(entry).toHaveTextContent(rule.population);
      for (const s of rule.sourceIds) expect(entry).toHaveTextContent(`${s}:`);
    }
    expect(screen.getAllByText('Expert opinion (OPINION)').length).toBeGreaterThan(0);
  });

  it('shows the answers of the person in Why this plan', () => {
    setup();
    const answers = screen.getByRole('list', { name: 'Your answers' });
    expect(answers).toHaveTextContent('2026-10-15');
    expect(answers).toHaveTextContent('Left');
    expect(answers).toHaveTextContent('60 degrees');
  });

  it('shows the value that the person entered as entered by the person, and the rest with its rule', () => {
    setup();
    const entry = screen.getByRole('heading', { name: RULES.RANGE_SURGEON.title, level: 3 }).closest('li') as HTMLElement;
    expect(entry).toHaveTextContent('60');
    expect(entry).toHaveTextContent('as entered by you');
  });

  it('lists what is not in the plan and why, with the ask your surgeon line', () => {
    setup();
    const refused = screen.getByRole('list', { name: 'Not in your plan, and why' });
    for (const id of ['SQUAT', 'HOLD', 'RANGE_NONE', 'NONE_WB_BRACE'] as const) {
      expect(within(refused).getByRole('heading', { name: RULES[id].title, level: 3 })).toBeInTheDocument();
    }
    expect(within(refused).getAllByText('Ask your surgeon').length).toBeGreaterThan(0);
  });

  it('flags the values that no clinician reviewed', () => {
    setup();
    const flagged = screen.getAllByText('A clinician has not reviewed this value.');
    expect(flagged.length).toBeGreaterThan(0);
  });

  it('presses Use this plan and Back, and saves nothing by itself', () => {
    const { onUse, onBack } = setup();
    fireEvent.click(screen.getByRole('button', { name: 'Use this plan' }));
    expect(onUse).toHaveBeenCalledTimes(1);
    fireEvent.click(screen.getByRole('button', { name: 'Back' }));
    expect(onBack).toHaveBeenCalledTimes(1);
  });

  it('has no inline style, hides every icon, and holds no verdict word', () => {
    const { view } = setup();
    expect(view.container.querySelector('[style]')).toBeNull();
    for (const svg of view.container.querySelectorAll('svg')) expect(svg).toHaveAttribute('aria-hidden', 'true');
    expect(hasVerdictWord(view.container.textContent ?? '')).toBeNull();
  });

  it('shows the phase 2 plan when the clearance answer is yes', () => {
    setup({ surgeryDate: '2026-09-15', phaseClearance: 'yes' });
    expect(screen.getByText('Phase 2 Strengthening')).toBeInTheDocument();
  });
});

describe('values that no guideline gives', () => {
  const open = (title: string) => {
    const entry = screen.getByRole('heading', { name: title, level: 3 }).closest('li') as HTMLElement;
    return entry;
  };

  it('shows the plain line and the words of the guideline in each rule of kind none, and the line in no rule that holds a number', () => {
    setup();
    for (const title of ['Knee-bend ceiling', 'Hold time', 'Repetition tempo', 'Session frequency', 'Numeric pain or swelling stop', 'Weight-bearing and brace']) {
      const entry = open(title);
      expect(within(entry).getByText('No number in the guideline.'), title).toBeInTheDocument();
    }
    expect(open('Knee-bend ceiling')).toHaveTextContent('passive range targets');
    expect(open('Hold time')).toHaveTextContent('test of the straight leg raise');
    expect(within(open('Straight leg raise')).queryByText('No number in the guideline.')).toBeNull();
    expect(within(open('Dose of the strengthening exercise')).queryByText('No number in the guideline.')).toBeNull();
  });

  it('shows the reference for the knee bend by week once, as a source note with evidence, population and the label, and as typical practice', () => {
    const { container } = setup().view;
    expect(container.querySelectorAll('.range-reference')).toHaveLength(1);
    const note = screen.getByLabelText('Source of: Knee bend by week');
    const lines = within(note).getAllByRole('listitem').map((li) => li.textContent ?? '');
    expect(lines[0]).toMatch(/^Source: Hsu CJ, Lee C, Christensen RS, Liu TY, 2025|^Source: Hsu/);
    expect(lines[1]).toBe('Evidence: OPINION (level 5, clinical commentary)');
    expect(lines[2]).toMatch(/^Population: Isolated and combined MPFL reconstruction, no age limit stated/);
    expect(lines[3]).toBe('Not approved by a clinician. No clinician has reviewed this value.');
    const root = container.querySelector('.range-reference') as HTMLElement;
    expect(root).toHaveTextContent('Typical practice in the guideline, not a limit and not your plan:');
    expect(root).toHaveTextContent('Your surgeon sets your limit.');
    expect(container.textContent).not.toMatch(/add 20 to 30|week 3 |week 4 |undefined|NaN/);
  });
});

describe('A-17: the chip of a rule that is not in the plan matches its own line', () => {
  const chipOf = (title: string) => {
    const entry = screen.getByRole('heading', { name: title, level: 3 }).closest('li') as HTMLElement;
    return { entry, chip: entry.querySelector('.why-head .chip-accent')?.textContent ?? null };
  };

  it('names the care team where the text says care team, the surgeon where it says surgeon, and shows no chip where it names neither', () => {
    setup();
    for (const title of ['Session frequency', 'Repetition tempo', 'Hold time']) expect(chipOf(title).chip, title).toBe('Ask your care team');
    expect(chipOf('Weight-bearing and brace').chip).toBe('Ask your surgeon');
    expect(chipOf('Knee-bend ceiling').chip).toBe('Ask your surgeon');
    expect(chipOf('Dose of the heel slide and the ankle pump').chip).toBe('Ask your care team');
    const pause = chipOf('Pain and swelling pause');
    expect(pause.chip).toBeNull();
    expect(pause.entry).toHaveTextContent('The pause rule of the app stays');
  });

  it('never shows a chip that the text of the line does not support', () => {
    setup();
    for (const li of document.querySelectorAll('.why-list[aria-label="Not in your plan, and why"] .why-entry')) {
      const chip = li.querySelector('.why-head .chip-accent')?.textContent;
      if (chip) expect(li.querySelector('.why-body p')?.textContent).toContain(chip);
    }
  });
});
