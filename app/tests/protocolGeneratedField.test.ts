import example from '../src/lib/protocol/example-protocol.json';
import { createProtocolStore, loadProtocol } from '../src/lib/protocol';
import { protocolSchema } from '../src/lib/protocol/schema';

const base = {
  schemaVersion: 1,
  id: 'g-001',
  side: 'left',
  authoredBy: 'Generated by the app from published protocols',
  activePhase: 1,
  phases: [{ id: 1, name: 'Protection', exercises: [{ kind: 'straight-leg-raise', source: 'S1' }] }],
  surgeon: {},
};
const generated = { on: '2026-11-08', rules: '2026-11-08' };
const text = (o: unknown) => JSON.stringify(o);

describe('the optional generated field', () => {
  it('accepts a generated mark with a date and a rules version', () => {
    expect(protocolSchema.safeParse({ ...base, generated }).success).toBe(true);
  });

  it('keeps every file without the field valid, with no default', () => {
    const r = protocolSchema.safeParse(base);
    expect(r.success).toBe(true);
    expect(r.success && r.data.generated).toBeUndefined();
    expect(protocolSchema.safeParse(example).success).toBe(true);
  });

  it.each([
    ['an unknown key', { ...generated, by: 'x' }],
    ['a date that is not a date', { ...generated, on: 'yesterday' }],
    ['a rules text over 20 characters', { ...generated, rules: 'x'.repeat(21) }],
    ['a rules value that is not text', { ...generated, rules: 3 }],
    ['no date', { rules: 'v1' }],
    ['no rules', { on: '2026-11-08' }],
  ])('rejects %s', (_name, value) => {
    expect(protocolSchema.safeParse({ ...base, generated: value }).success).toBe(false);
  });

  it('rejects generated together with example', () => {
    expect(protocolSchema.safeParse({ ...base, example: true, generated }).success).toBe(false);
  });
});

describe('the loader and the store keep the generated field', () => {
  const approvedGenerated = { ...base, generated, approvedOn: '2026-11-09' };

  it('loads a generated plan that a clinician approved, in patient mode, and keeps the mark', () => {
    const r = loadProtocol(text(approvedGenerated), 'patient');
    expect(r.ok && r.protocol.generated).toEqual(generated);
    expect(r.ok && r.protocol.approvedOn).toBe('2026-11-09');
  });

  it('refuses a generated plan without an approval in patient mode', () => {
    const r = loadProtocol(text({ ...base, generated }), 'patient');
    expect(r).toMatchObject({ ok: false, error: { code: 'not-approved' } });
  });

  it('loads a generated plan without an approval in demo mode and keeps the mark', () => {
    const r = loadProtocol(text({ ...base, generated }), 'demo');
    expect(r.ok && r.protocol.generated).toEqual(generated);
  });

  it('keeps the mark in the store', () => {
    const r = loadProtocol(text(approvedGenerated), 'demo');
    if (!r.ok) throw new Error('expected a loaded protocol');
    expect(createProtocolStore(r.protocol).protocol.generated).toEqual(generated);
  });
});
