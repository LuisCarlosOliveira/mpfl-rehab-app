// The app mode and the banners. Without the build flag, the app is a prototype:
// every screen shows the prototype banner and the example protocol can load.
// With the flag, patient mode refuses the example and an unapproved protocol.
// Only a clinician review and an expert decision on the regulatory class allow the flag.

import type { Mode } from './protocol';

export const PROTOTYPE_BANNER = 'Prototype. Not for patient use.';
export const EXAMPLE_BANNER = 'EXAMPLE, NOT APPROVED';
export const GENERATED_BANNER = 'Generated by the app from published protocols. Not approved by a clinician.';

/** `flag` is the value of VITE_PATIENT_USE_APPROVED. Only the exact text "true" turns on patient mode. */
export function appMode(flag: string | undefined): Mode {
  return flag === 'true' ? 'patient' : 'demo';
}

/** The banner texts that every screen shows. `generatedUnapproved` is true for a stored plan that the app made and no clinician approved. */
export function bannersFor(mode: Mode, protocolIsExample: boolean, generatedUnapproved = false): string[] {
  const banners: string[] = [];
  if (mode === 'demo') banners.push(PROTOTYPE_BANNER);
  if (protocolIsExample) banners.push(EXAMPLE_BANNER);
  if (generatedUnapproved) banners.push(GENERATED_BANNER);
  return banners;
}

/**
 * The extended generator items (the mini squat, the seated hold, the questions about walking, the leg raise and the clearance of the hold,
 * and the phase 2 heel slide for an unknown limit) are on by default. The app proposes the full plan from the guidelines (decision of the user, 2026-11-11).
 * Only the exact text "false" or "0" in VITE_GENERATOR_EXTENDED turns them off.
 */
export const generatorExtendedOn = (): boolean => {
  const flag = import.meta.env.VITE_GENERATOR_EXTENDED;
  return flag !== 'false' && flag !== '0';
};
