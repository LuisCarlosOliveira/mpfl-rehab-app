// The pure core of the protocol generator. It reads answers and a date and returns a plan or a referral.
// It saves nothing, reads no clock and writes no active phase. The person confirms a plan elsewhere.
// It fails closed: any exception and any schema failure give a referral.

import { evaluateRedFlags } from '../redflags';
import { generatorExtendedOn } from '../mode';
import { evaluateSession } from '../safety';
import { protocolSchema, type Exercise, type HomeExercise, type Protocol } from '../protocol/schema';
import { inputsSchema, type GeneratorInputs } from './inputs';
import { DOSE_SHOWN, NOT_APPROVED, RULES, type RuleId } from './rules';
import type { Grade, SourceId } from './sources';

export const GENERATED_BY = 'Generated by the app from published protocols';

export type ReferralId = 'R1' | 'R2' | 'R3' | 'R4' | 'R5' | 'R6' | 'R7' | 'R8' | 'R9' | 'R10' | 'RX';

export interface Applied {
  /** For example `phase1.straight-leg-raise.sets`. */
  path: string;
  value: number | string;
  origin: 'rule' | 'person';
}

export interface WhyEntry {
  ruleId: RuleId;
  sourceIds: readonly SourceId[];
  grade: Grade;
  population: string;
  conservative?: string;
  text: string;
  label: typeof NOT_APPROVED;
  outcome: 'generated' | 'refused';
  flag?: 'clinical-review-needed';
  applied: Applied[];
}

export type GenerateResult =
  | { kind: 'protocol'; protocol: Protocol; why: WhyEntry[] }
  | { kind: 'referral'; reason: ReferralId; text: string };

const DAY_MS = 86_400_000;

/** Day number of an ISO date, or null when the text is not a real calendar date. */
function dayNumber(iso: string): number | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(iso)) return null;
  const ms = Date.parse(`${iso}T00:00:00Z`);
  if (Number.isNaN(ms) || new Date(ms).toISOString().slice(0, 10) !== iso) return null;
  return ms / DAY_MS;
}

const isoOf = (day: number) => new Date(day * DAY_MS).toISOString().slice(0, 10);

function refer(id: ReferralId, extra?: string): GenerateResult {
  const base = RULES[id].referralText as string;
  return { kind: 'referral', reason: id, text: extra === undefined ? base : `${base} ${extra}` };
}

function why(id: RuleId, outcome: WhyEntry['outcome'], applied: Applied[] = []): WhyEntry {
  const r = RULES[id];
  return {
    ruleId: id,
    sourceIds: r.sourceIds,
    grade: r.grade,
    population: r.population,
    conservative: r.conservative,
    text: r.text,
    label: NOT_APPROVED,
    outcome,
    flag: r.flag,
    applied,
  };
}

function build(raw: GeneratorInputs, today: string): GenerateResult {
  const i = inputsSchema.parse(raw);
  const todayDay = dayNumber(today);
  if (todayDay === null) return refer('RX');

  const flags = evaluateRedFlags(i.redFlags);
  if (flags.blocked) return refer('R8', flags.message);
  const session = evaluateSession({ pain: i.pain, swelling: i.swelling });
  if (session.pause) return refer('R9', session.message ?? '');

  if (i.writtenPlan !== 'no') return refer('R1');
  if (i.procedure !== 'mpflr-only') return refer('R2');
  if (i.ageBand === 'under-18') return refer('R3');
  if (i.bothKnees) return refer('R4');
  if (i.firstSurgery !== 'yes') return refer('R5');
  if (i.specialRules !== 'no') return refer('R6');
  const surgeryDay = i.surgeryDate === null ? null : dayNumber(i.surgeryDate);
  if (surgeryDay === null || surgeryDay > todayDay) return refer('R7');

  const week = Math.floor((todayDay - surgeryDay) / 7);
  if (week > RULES.W1.values.lastWeek) return refer('R10');

  const phase2 = week >= RULES.PH2.values.firstWeek && i.phaseClearance === 'yes';
  const extended = generatorExtendedOn(); // the mini squat, the seated hold and the unknown-limit heel slide are held back without it
  const limit = i.surgeonLimit;
  const target = RULES.ENG_TARGET.values.targetFlexion;
  const back = RULES.ENG_RETURN.values.returnWithinDeg;
  const lowestLimit = RULES.ENG_TARGET.values.minLimit;

  const doseApplied: Applied[] = [];
  const targetApplied: Applied[] = [];
  const returnApplied: Applied[] = [];
  const limitApplied: Applied[] = [];
  const reviewApplied: Applied[] = [];

  // The dose of every strengthening exercise (P2 rec 26, Note 1: all strengthening exercises, all phases).
  // The schema needs one number, so the field holds the start of the range. The source line and the plan text show the whole range.
  const dosed = (path: string): { sets: number; reps: number } => {
    const { sets, reps } = RULES.DOSE.values;
    doseApplied.push({ path: `${path}.sets`, value: sets, origin: 'rule' }, { path: `${path}.reps`, value: reps, origin: 'rule' });
    return { sets, reps };
  };
  const doseSource = `${DOSE_SHOWN}: P2 rec 26 (DOSE), OPINION (level 5), ages 8 to 25. ${NOT_APPROVED}.`;

  const straightLegRaise = (phaseId: number): Exercise => ({
    kind: 'straight-leg-raise',
    ...dosed(`phase${phaseId}.straight-leg-raise`),
    source: `Name: S1 (SLR). ${doseSource}`,
  });

  // The home exercises that the camera does not count. Ankle pumps are in phase 1 only (P1, P3).
  const homeExercises = (phaseId: number): HomeExercise[] => {
    const named = (kind: HomeExercise['kind'], names: string): HomeExercise => ({ kind, ...dosed(`phase${phaseId}.${kind}`), source: `${names} (HOME). ${doseSource}` });
    return [
      named('quad-set', 'Quadriceps set: S1 P1 P2 P3 N3'),
      named('gluteal-set', 'Gluteal set: P1 P2 N3'),
      ...(phaseId === 1
        ? [{ kind: 'ankle-pump' as const, source: `Ankle pump: P1 P3 (ANKLE). No dose (DOSE_NONE). ${NOT_APPROVED}.` }]
        : []),
      named('leg-raise-side', 'Leg raise to the side: S1 P1 P2 P3'),
      named('leg-raise-back', 'Leg raise to the back: S1 P1 P2 P3'),
    ];
  };

  // The heel slide needs a number from the surgeon in phase 1. In phase 2 "no limit" and "unknown" also add it.
  const heelSlide = (phaseId: number): Exercise | null => {
    if (limit.kind === 'unknown' && (phaseId === 1 || !extended)) return null;
    if (limit.kind === 'none' && phaseId === 1) return null;
    if (limit.kind === 'degrees' && limit.degrees < lowestLimit) return null;
    const path = `phase${phaseId}.heel-slide`;
    targetApplied.push({ path: `${path}.targetFlexion`, value: target, origin: 'rule' });
    returnApplied.push({ path: `${path}.returnWithinDeg`, value: back, origin: 'rule' });
    const common = { kind: 'heel-slide' as const, targetFlexion: target, returnWithinDeg: back };
    const tail = `Target and return: ENGINEERING (ENG_TARGET ENG_RETURN). No dose. ${NOT_APPROVED}.`;
    if (limit.kind === 'degrees') {
      limitApplied.push({ path: `${path}.maxFlexion`, value: limit.degrees, origin: 'person' });
      return { ...common, maxFlexion: limit.degrees, source: `Heel slide: S1 P3 P1 (HEEL). Limit: your surgeon, as entered (RANGE_SURGEON). ${tail}` };
    }
    if (limit.kind === 'unknown') return { ...common, source: `Heel slide: S1 P3 P1 (HEEL_P2_UNKNOWN). Limit not known, no ceiling. ${tail}` };
    return { ...common, source: `Heel slide: S1 P3 P1 (HEEL). No limit entered. ${tail}` };
  };

  // Mini squat (D1). From phase 2, with both answers yes and no knee gave way event. The app sets no depth.
  // Only a limit from the surgeon, as entered by the person, is the ceiling.
  const squatBuilt =
    extended && phase2 && i.walksWithoutCrutches === 'yes' && i.legRaiseStraight === 'yes' && !i.kneeGaveWay && (limit.kind !== 'degrees' || limit.degrees >= lowestLimit);
  const miniSquat = (): Exercise => {
    const path = 'phase2.mini-squat';
    targetApplied.push({ path: `${path}.targetFlexion`, value: target, origin: 'rule' });
    returnApplied.push({ path: `${path}.returnWithinDeg`, value: back, origin: 'rule' });
    if (limit.kind === 'degrees') limitApplied.push({ path: `${path}.maxFlexion`, value: limit.degrees, origin: 'person' });
    return {
      kind: 'mini-squat',
      ...dosed(path),
      targetFlexion: target,
      ...(limit.kind === 'degrees' ? { maxFlexion: limit.degrees } : {}),
      returnWithinDeg: back,
      source: `Mini squat: P3 P2 N3 S1 (SQUAT_P2). Depth: your surgeon or none. Dose: ${DOSE_SHOWN} (DOSE). Count: ENGINEERING. ${NOT_APPROVED}.`,
    };
  };

  const exercisesOf = (phaseId: number): Exercise[] => {
    const list = [straightLegRaise(phaseId)];
    const heel = heelSlide(phaseId);
    if (heel !== null) list.push(heel);
    if (phaseId === 2 && squatBuilt) list.push(miniSquat());
    return list;
  };

  const phase1Date = isoOf(surgeryDay + 7 * RULES.REVIEW.values.phase1Weeks);
  const phase2Date = isoOf(surgeryDay + 7 * RULES.REVIEW.values.phase2Weeks);
  reviewApplied.push({ path: 'phase1.reviewDate', value: phase1Date, origin: 'rule' });

  const phases: Protocol['phases'] = [
    {
      id: 1,
      name: 'Protection',
      exercises: exercisesOf(1),
      homeExercises: homeExercises(1),
      reviewCriteria: [
        { kind: 'clinicianCheck', key: 'extensionFull', evidence: 'mpflr' },
        { kind: 'clinicianCheck', key: 'slrNoLag', evidence: 'mpflr' },
        { kind: 'clinicianCheck', key: 'gait', evidence: 'mpflr' },
      ],
      reviewDate: phase1Date,
    },
  ];
  if (phase2) {
    reviewApplied.push({ path: 'phase2.reviewDate', value: phase2Date, origin: 'rule' });
    phases.push({ id: 2, name: 'Strengthening', exercises: exercisesOf(2), homeExercises: homeExercises(2), reviewDate: phase2Date });
  }

  const hasHeel = phases.some((p) => p.exercises.some((e) => e.kind === 'heel-slide'));
  const heelUnknown = phase2 && extended && limit.kind === 'unknown';
  const entries: WhyEntry[] = [
    why('W1', 'generated'),
    why('PH1', 'generated'),
    ...(week >= RULES.PH2.values.firstWeek ? [why('PH2', phase2 ? 'generated' : 'refused')] : []),
    why('SLR', 'generated'),
    why('HOME', 'generated'),
    why('ANKLE', 'generated'),
    why('DOSE', 'generated', doseApplied),
    why('HEEL', hasHeel ? 'generated' : 'refused'),
    ...(heelUnknown ? [why('HEEL_P2_UNKNOWN', 'generated')] : []),
    ...(limitApplied.length > 0 ? [why('RANGE_SURGEON', 'generated', limitApplied)] : []),
    ...(phase2 && !extended ? [why('EXTENDED_OFF', 'refused')] : []),
    ...(phase2 && extended ? [why('SQUAT_P2', squatBuilt ? 'generated' : 'refused'), why('SQUAT_GATE', squatBuilt ? 'generated' : 'refused')] : []),
    ...(targetApplied.length > 0 ? [why('ENG_TARGET', 'generated', targetApplied), why('ENG_RETURN', 'generated', returnApplied)] : []),
    why('REVIEW', 'generated', reviewApplied),
    ...(week <= RULES.PH1.values.lastWeek ? [why('ROM_CHECK', 'generated')] : []),
    why('PT_VISITS', 'generated'),
    why('RANGE_NONE', 'refused'),
    why('DOSE_NONE', 'refused'),
    why('SQUAT', 'refused'),
    why('HOLD', 'refused'),
    why('PAIN', 'refused'),
    ...(['NONE_WB_BRACE', 'NONE_FREQ', 'NONE_TEMPO', 'NONE_HOLDTIME', 'NONE_PAIN_STOP', 'NONE_VALGUS', 'NONE_REVISION', 'NONE_GRAFT'] as const).map(
      (id) => why(id, 'refused'),
    ),
  ];
  const protocol = protocolSchema.parse({
    schemaVersion: 1,
    id: `generated-week-${week}`,
    side: i.side,
    authoredBy: GENERATED_BY,
    generated: { on: today, rules: [...new Set(entries.filter((e) => e.outcome === 'generated').map((e) => e.ruleId))] },
    activePhase: phase2 ? 2 : 1,
    phases,
    surgeon: {
      concurrentProcedures: 'None, as entered by you',
      ...(phase2 ? { phaseClearance: 'Reported by you. Not checked by the app.' } : {}),
    },
  });

  return { kind: 'protocol', protocol, why: entries };
}

/** Make a plan from the answers of the person, or a referral. `today` is an ISO date. */
export function generateProtocol(inputs: GeneratorInputs, today: string): GenerateResult {
  try {
    return build(inputs, today);
  } catch {
    return refer('RX');
  }
}
